//! Static scene image layers. Coordinates and angles use Wallpaper Engine's
//! scene units (Y up, radians), including inherited parent transforms.
use super::{Assets, DynamicImage, Value, MAX_ASSET, layer_texture, property, texture_image, vector};

#[derive(Clone, Copy)]
struct Transform { a: f32, b: f32, c: f32, d: f32, x: f32, y: f32 }
impl Transform {
    fn point(self, x: f32, y: f32) -> (f32,f32) { (self.a*x+self.c*y+self.x,self.b*x+self.d*y+self.y) }
    fn combine(self, other: Self) -> Self {
        let (x,y)=self.point(other.x,other.y);
        Self { a:self.a*other.a+self.c*other.b,b:self.b*other.a+self.d*other.b,
            c:self.a*other.c+self.c*other.d,d:self.b*other.c+self.d*other.d,x,y }
    }
    fn inverse(self) -> Option<Self> {
        let det=self.a*self.d-self.b*self.c;
        if !det.is_finite() || det.abs()<0.000001 { return None; }
        let (a,b,c,d)=(self.d/det,-self.b/det,-self.c/det,self.a/det);
        Some(Self {a,b,c,d,x:-a*self.x-c*self.y,y:-b*self.x-d*self.y})
    }
}

fn world(object: &Value, objects: &[Value], visited: &mut Vec<i64>) -> Option<Transform> {
    if property(&object["visible"]).as_bool()==Some(false) || visited.len()>=16 { return None; }
    let origin=vector(&object["origin"],[0.0;3]);
    let scale=vector(&object["scale"],[1.0;3]);
    let angles=vector(&object["angles"],[0.0;3]);
    let (sin,cos)=angles[2].sin_cos();
    let (sx,sy)=(scale[0]*angles[1].cos(),scale[1]*angles[0].cos());
    let local=Transform { a:cos*sx,b:sin*sx,c:-sin*sy,d:cos*sy,x:origin[0],y:origin[1] };
    let Some(parent)=object["parent"].as_i64() else { return Some(local); };
    if visited.contains(&parent) { return None; }
    visited.push(parent);
    let parent=objects.iter().find(|object| object["id"].as_i64()==Some(parent))?;
    Some(world(parent,objects,visited)?.combine(local))
}

pub(super) struct Composition { pub image: DynamicImage, pub reliable: bool }

pub(super) fn render(assets: &mut Assets, scene: &Value) -> Option<Composition> {
    let projection=&scene["general"]["orthogonalprojection"];
    let (width,height)=(projection["width"].as_f64()? as f32,projection["height"].as_f64()? as f32);
    if !width.is_finite() || !height.is_finite() || width<1.0 || height<1.0 || width/height>8.0 || height/width>8.0 { return None; }
    let objects=scene["objects"].as_array()?;
    // A partial background is not a cover for a 3D model scene.
    if objects.iter().any(|object| object["model"].is_string() && property(&object["visible"]).as_bool()!=Some(false)) { return None; }
    let ratio=(2560.0/width.max(height)).min(1.0);
    let (w,h)=((width*ratio).round().max(1.0) as u32,(height*ratio).round().max(1.0) as u32);
    let background=vector(&scene["general"]["clearcolor"],[0.0;3]).map(|v| (v.clamp(0.0,1.0)*255.0).round() as u8);
    let mut canvas=image::RgbaImage::from_pixel(w,h,image::Rgba([background[0],background[1],background[2],255]));
    let (mut layers,mut has_hd_main,mut incomplete)=(0,false,false);
    let mut pixels_processed=0u64;
    for object in objects.iter().take(1024) {
        let Some(transform)=world(object,objects,&mut Vec::new()) else { continue; };
        let Some(inverse)=transform.inverse() else { continue; };
        let alpha=property(&object["alpha"]).as_f64().unwrap_or(1.0).clamp(0.0,1.0) as f32;
        if alpha==0.0 { continue; }
        let Some(name)=layer_texture(assets,object) else { continue; };
        let size=vector(&object["size"],[0.0;3]);
        // Built-in render targets are generated by the engine, not missing
        // artwork. They must not disqualify an otherwise complete HD scene.
        let Some(bytes)=assets.read(&name,MAX_ASSET,false) else { continue; };
        let flags=bytes.get(22..26).and_then(|bytes| <[u8;4]>::try_from(bytes).ok()).map(u32::from_le_bytes).unwrap_or(0);
        // Animated video overlays (birds, rain, etc.) do not prevent a sharp
        // static cover of the HD background underneath them.
        if flags & 32 != 0 { continue; }
        let Some(image)=texture_image(&bytes) else {
            if size[0]*size[1]>=width*height*0.25 { incomplete=true; }
            continue;
        };
        let size=vector(&object["size"],[image.width() as f32,image.height() as f32,0.0]);
        if size[0]<1.0 || size[1]<1.0 { continue; }
        let corners=[(-0.5,-0.5),(-0.5,0.5),(0.5,-0.5),(0.5,0.5)].map(|(x,y)| {
            let (x,y)=transform.point(x*size[0],y*size[1]); (x*ratio,(height-y)*ratio)
        });
        let left=corners.iter().map(|p| p.0).fold(f32::INFINITY,f32::min).floor().max(0.0).min(w as f32) as u32;
        let top=corners.iter().map(|p| p.1).fold(f32::INFINITY,f32::min).floor().max(0.0).min(h as f32) as u32;
        let right=corners.iter().map(|p| p.0).fold(f32::NEG_INFINITY,f32::max).ceil().max(0.0).min(w as f32) as u32;
        let bottom=corners.iter().map(|p| p.1).fold(f32::NEG_INFINITY,f32::max).ceil().max(0.0).min(h as f32) as u32;
        if right<=left || bottom<=top { continue; }
        let area=(right-left) as u64*(bottom-top) as u64;
        pixels_processed+=area;
        if layers>=64 || pixels_processed>96_000_000 { incomplete=true; break; }
        let opacity=image.thumbnail(32,32).to_rgba8().pixels().map(|p| p[3] as f64).sum::<f64>()/255.0/1024.0;
        if image.height()>=720 && image.width() as u64*image.height() as u64>=900_000 && area as f64>=w as f64*h as f64*0.45 && opacity>0.08 { has_hd_main=true; }
        let image=image.to_rgba8();
        let colour=vector(&object["color"],[1.0;3]);
        for y in top..bottom {
            for x in left..right {
                let (u,v)=inverse.point((x as f32+0.5)/ratio,height-(y as f32+0.5)/ratio);
                let (u,v)=((u/size[0]+0.5)*image.width() as f32-0.5,(0.5-v/size[1])*image.height() as f32-0.5);
                if u< -0.5 || v< -0.5 || u>=image.width() as f32-0.5 || v>=image.height() as f32-0.5 { continue; }
                let (u,v)=(u.max(0.0),v.max(0.0));
                let (ix,iy)=(u.floor() as u32,v.floor() as u32);
                let (fx,fy)=(u-ix as f32,v-iy as f32);
                let mut sample=[0.0f32;4];
                for (dx,dy,weight) in [(0,0,(1.0-fx)*(1.0-fy)),(1,0,fx*(1.0-fy)),(0,1,(1.0-fx)*fy),(1,1,fx*fy)] {
                    let pixel=image.get_pixel((ix+dx).min(image.width()-1),(iy+dy).min(image.height()-1));
                    let a=pixel[3] as f32/255.0*weight;
                    for c in 0..3 { sample[c]+=pixel[c] as f32*a; }
                    sample[3]+=a;
                }
                let destination=canvas.get_pixel_mut(x,y);
                let a=(sample[3]*alpha).clamp(0.0,1.0);
                for c in 0..3 { destination[c]=(sample[c]*colour[c]*alpha+destination[c] as f32*(1.0-a)).clamp(0.0,255.0).round() as u8; }
            }
        }
        layers+=1;
    }
    #[cfg(test)]
    if !has_hd_main || incomplete { eprintln!("COMPOSITION layers={layers}, hd_main={has_hd_main}, incomplete={incomplete}, processed={pixels_processed}"); }
    (layers>0).then_some(Composition { image:DynamicImage::ImageRgba8(canvas),reliable:has_hd_main && !incomplete })
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn parent_rotation_uses_radians_and_inherits_translation_and_scale() {
        let objects=vec![serde_json::json!({"id":1,"origin":"100 50 0","angles":format!("0 0 {}",std::f32::consts::FRAC_PI_2),"scale":"2 3 1"}),
            serde_json::json!({"id":2,"parent":1,"origin":"10 0 0"})];
        let transform=world(&objects[1],&objects,&mut Vec::new()).unwrap();
        let (x,y)=transform.point(0.0,0.0);
        assert!((x-100.0).abs()<0.001 && (y-70.0).abs()<0.001);
        let inverse=transform.inverse().unwrap();
        let point=transform.point(4.0,7.0);
        let local=inverse.point(point.0,point.1);
        assert!((local.0-4.0).abs()<0.001 && (local.1-7.0).abs()<0.001);
    }
    #[test]
    fn hidden_parents_and_cycles_cannot_render_children() {
        let objects=vec![serde_json::json!({"id":1,"visible":{"value":false}}),serde_json::json!({"id":2,"parent":1})];
        assert!(world(&objects[1],&objects,&mut Vec::new()).is_none());
        let cycle=vec![serde_json::json!({"id":1,"parent":2}),serde_json::json!({"id":2,"parent":1})];
        assert!(world(&cycle[0],&cycle,&mut Vec::new()).is_none());
    }
}
